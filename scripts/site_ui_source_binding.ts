/** Bind the Vite entry used by the static exporter to the source and preview mode it compiled. */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

export const UI_SOURCE_META = "neotoma-ui-source";
export const UI_HEAD_META = "neotoma-ui-head";
export const UI_MODE_META = "neotoma-ui-mode";

const TRUSTED_READER_ASSET = "public/assets/reader-language.js";
// Vite's generateBundle hook checks that every compiled local module is inside this inventory.
// The explicit reader asset is outside Vite's module graph but trusted by static reader chrome.
// public/brand is generated by Vite from tracked frontend/public/brand, after HTML transforms run.
const SOURCE_DIRS = ["frontend/src", "frontend/public", "src", "docs/site/pages", "docs/legal"];
const SOURCE_FILES = ["frontend/index.html", "openapi_actions.yaml", "vite.config.ts", "package.json", "package-lock.json", "scripts/site_ui_source_binding.ts", TRUSTED_READER_ASSET];

export function assertTrackedReaderLanguageAsset(repoRoot: string, exportedSite?: string) {
  const committed = execFileSync("git", ["show", `HEAD:${TRUSTED_READER_ASSET}`], { cwd: repoRoot });
  const current = fs.readFileSync(path.join(repoRoot, TRUSTED_READER_ASSET));
  if (!current.equals(committed))
    throw new Error("Trusted reader language asset differs from the committed source");
  if (exportedSite && !fs.readFileSync(path.join(exportedSite, "assets/reader-language.js")).equals(committed))
    throw new Error("Exported reader language asset differs from the committed source");
}

export function uncoveredUiModules(repoRoot: string, moduleIds: Iterable<string>): string[] {
  const covered = (relative: string) => SOURCE_FILES.includes(relative) ||
    SOURCE_DIRS.some((dir) => relative.startsWith(`${dir}/`));
  const uncovered = new Set<string>();
  for (const id of moduleIds) {
    const clean = id.split("?")[0];
    if (!path.isAbsolute(clean)) continue; // Vite virtual modules are not source files.
    const relative = path.relative(repoRoot, clean).replaceAll(path.sep, "/");
    if (relative.startsWith("../") || relative === ".." || relative.startsWith("node_modules/")) continue;
    if (!covered(relative)) uncovered.add(relative);
  }
  return [...uncovered].sort();
}

export function currentUiSourceBinding(repoRoot: string) {
  assertTrackedReaderLanguageAsset(repoRoot);
  const head = execFileSync("git", ["rev-parse", "HEAD"], { cwd: repoRoot, encoding: "utf8" }).trim();
  const files = [...SOURCE_FILES];
  const walk = (relative: string) => {
    const absolute = path.join(repoRoot, relative);
    for (const entry of fs.readdirSync(absolute, { withFileTypes: true })) {
      const child = path.posix.join(relative, entry.name);
      if (entry.isDirectory()) walk(child);
      else if (entry.isFile()) files.push(child);
      else throw new Error(`Unsupported UI source entry: ${child}`);
    }
  };
  for (const dir of SOURCE_DIRS) walk(dir);
  const hash = createHash("sha256").update(`${head}\0`);
  for (const relative of files.sort()) {
    hash.update(relative).update("\0");
    hash.update(fs.readFileSync(path.join(repoRoot, relative))).update("\0");
  }
  return { head, source: hash.digest("hex") };
}

export function currentUiMode(): "preview" | "public" {
  return process.env.VITE_SITE_PREVIEW === "1" ? "preview" : "public";
}

function meta(html: string, name: string): string | null {
  const tags = [...html.matchAll(/<meta\b[^>]*>/gi)].map(([tag]) => tag);
  const matched = tags.filter((tag) => new RegExp(`\\bname=["']${name}["']`).test(tag));
  if (matched.length !== 1) return null;
  return /\bcontent=["']([^"']+)["']/.exec(matched[0])?.[1] ?? null;
}

export function readUiEntry(html: string): string {
  const entries = [...html.matchAll(/<script\b[^>]*\btype="module"[^>]*\bsrc="(\/assets\/main-[^"/]+\.js)"[^>]*><\/script>/gi)].map((m) => m[1]);
  if (entries.length !== 1) throw new Error("UI build has no unique Vite main entry");
  return entries[0];
}

export function assertUiSourceBinding(html: string, repoRoot: string, expectedMode?: "preview" | "public") {
  const current = currentUiSourceBinding(repoRoot);
  if (meta(html, UI_HEAD_META) !== current.head || meta(html, UI_SOURCE_META) !== current.source)
    throw new Error("UI build source binding is stale; run npm run build:ui before the static export");
  const mode = meta(html, UI_MODE_META);
  if (mode !== "preview" && mode !== "public")
    throw new Error("UI build mode binding is missing or invalid; run npm run build:ui");
  if (expectedMode && mode !== expectedMode)
    throw new Error(`UI build mode ${mode} does not match static export mode ${expectedMode}`);
  const entry = readUiEntry(html);
  const entryFile = path.join(repoRoot, "public", entry.slice(1));
  if (!fs.statSync(entryFile, { throwIfNoEntry: false })?.isFile())
    throw new Error(`UI build entry is missing: ${entry}`);
  return { ...current, mode, entry, entrySha256: createHash("sha256").update(fs.readFileSync(entryFile)).digest("hex") };
}

export function assertExportedUiEntry(siteDir: string, repoRoot: string, routePaths: readonly string[]) {
  assertTrackedReaderLanguageAsset(repoRoot, siteDir);
  const publicHtml = fs.readFileSync(path.join(repoRoot, "public/index.html"), "utf8");
  const binding = assertUiSourceBinding(publicHtml, repoRoot);
  const exportedEntry = path.join(siteDir, binding.entry.slice(1));
  if (!fs.statSync(exportedEntry, { throwIfNoEntry: false })?.isFile() ||
      createHash("sha256").update(fs.readFileSync(exportedEntry)).digest("hex") !== binding.entrySha256)
    throw new Error("Static export entry asset does not match the source-bound Vite build");
  for (const route of routePaths) {
    const file = path.join(siteDir, route === "/" ? "index.html" : route.replace(/^\//, "").replace(/\/$/, "") + "/index.html");
    const html = fs.readFileSync(file, "utf8");
    if (readUiEntry(html) !== binding.entry || meta(html, UI_SOURCE_META) !== binding.source ||
        meta(html, UI_HEAD_META) !== binding.head || meta(html, UI_MODE_META) !== binding.mode)
      throw new Error(`Static export route ${route} does not match the source-bound Vite entry`);
  }
  return binding;
}
